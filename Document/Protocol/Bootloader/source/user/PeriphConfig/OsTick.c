/*
****************************************************************************************************
**
**                                           TickDelayMs()
**
**
**	功能描述: DelayMs 毫秒延时，用SysTick即可。
**
**	参  数  : nms为要延时的ms数
**
**	返回值  : 
**
**  备  注  : 
**
****************************************************************************************************
*/
void TickDelayMs(uint32 nMs)
{
	TickDelayUs(nMs * 1000);
}


/*
****************************************************************************************************
**
**                                           TickDelayUs()
**
**
**	功能描述: DelayUs 微秒延时。时间在1ms以下，超过1ms，就不要使用此函数。
**
**	参  数  : nUs为要延时的us数。nUs < 1000
**
**	返回值  : 
**
****************************************************************************************************
*/
void TickDelayUs(uint32 nUs)
{
	uint32 ticks;
	uint32 tOld, tNow, tCnt = 0;


	ticks = nUs * 192;							// 需要的节拍数
	tCnt  = 0;
	tOld  = (uint32)DWT_CYCCNT;	     	    	// 刚进入时的计数器值

	while (1)
	{
		tNow = (uint32)DWT_CYCCNT;
		
		if (tNow != tOld)
		{
			if (tNow > tOld)					// 32位计数器是递增计数器
			{
				tCnt += tNow - tOld;
			}
			else 								// 重新装载
			{
				tCnt += UINT32_MAX - tOld + tNow;
			}

			tOld = tNow;

			if (tCnt >= ticks)					// 时间超过/等于要延迟的时间,则退出
			{
				break;
			}
		}
	}
}


/*
****************************************************************************************************
**
**                                          TickDelay()
**
**
**	功能描述: 系统简单延时。程序中尽量不要用此函数，它受太多因素影响了。比如MCU主频，Keil代码优化
**            等级等等。
**
**	参  数  : nCount
**
**	返回值  : 
**
****************************************************************************************************
*/
void TickDelay(uint32 nCount)
{
	while (nCount--);
}




